function normalizeId(value: string): string {
  return value.toLowerCase().replace(/[^a-z0-9]/g, "");
}

export function includeChampionRoster(
  qualities: QualityDef[],
  characters: Character[],
  profiles: Readonly<Record<string, readonly number[]>>,
): Character[] {
  const included = new Set(
    characters.flatMap(({ id, name }) => [normalizeId(id), normalizeId(name)]),
  );

  return [
    ...characters,
    ...championNames
      .filter((name) => !included.has(normalizeId(name)))
      .map((name) => {
        const values = profiles[name];
        if (!values) {
          throw new Error(`Missing quiz trait profile for ${name}`);
        }
        if (values.length !== qualities.length) {
          throw new Error(
            `${name}: expected ${qualities.length} trait values, received ${values.length}`,
          );
        }
        if (values.some((value) => !Number.isFinite(value) || value < -1 || value > 1)) {
          throw new Error(`${name}: trait values must be finite and between -1 and 1`);
        }
        return character(
          qualities,
          normalizeId(name),
          name,
          "Champion",
          "A League of Legends champion from Runeterra.",
          [...values],
        );
      }),
  ];
}
